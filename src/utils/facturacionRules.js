/**
 * Función que cruza la Obra Social (cliente) y el Laboratorio
 * para determinar si el estado es FACTURAR o ENTREGAR.
 * Si no encuentra la regla, por defecto retorna '-'.
 */
export const getEstadoFacturacion = (obraSocial, laboratorio) => {
    if (!obraSocial || !laboratorio) return '-';
    
    // Buscar coincidencia en las reglas
    const clienteKey = Object.keys(REGLAS_FACTURACION).find(k => k.trim() === obraSocial.trim());
    
    if (!clienteKey) return '-'; // No existe regla para esa obra social

    const reglasLab = REGLAS_FACTURACION[clienteKey];

    if (laboratorio.includes('Aguero') || laboratorio.includes('Agüero') || laboratorio.includes('Rios')) return reglasLab.Aguero;
    if (laboratorio.includes('CEDAP')) return reglasLab.CEDAP;
    if (laboratorio.includes('CUYO') || laboratorio.includes('Cuyo')) return reglasLab.Cuyo;

    return '-';
};
